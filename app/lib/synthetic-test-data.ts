/**
 * Round-robin ordering prevents the topic-grouped source list from handing the
 * hierarchy to the model for free. Original numbers remain stable in exports.
 */
export const SYNTHETIC_TEST_THOUGHTS = Array.from(
  { length: Math.max(...TOPIC_RANGES.map(([start, end]) => end - start + 1)) },
  (_, offset) => TOPIC_RANGES
    .map(([start, end]) => start + offset <= end ? numbered[start + offset - 1] : undefined)
    .filter((item): item is (typeof numbered)[number] => Boolean(item)),
).flat();

export const SYNTHETIC_TEST_TOTAL = SYNTHETIC_TEST_THOUGHTS.length;

